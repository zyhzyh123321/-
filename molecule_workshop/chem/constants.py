# 理想键角（度），按中心原子杂化态
BOND_ANGLE: dict[str, float] = {"sp": 180.0, "sp2": 120.0, "sp3": 109.47}

_ORDER_SIGN = {1: "-", 2: "=", 3: "#"}


def bond_length(a: str, b: str, order: int = 1) -> float:
    """查平衡键长（Å）。任一顺序等价，如 C-O 与 O-C 相同。"""
    sign = _ORDER_SIGN.get(order, "-")
    for key in (f"{a}{sign}{b}", f"{b}{sign}{a}"):
        if key in BOND_LENGTH:
            return BOND_LENGTH[key]
    return DEFAULT_BOND_LENGTH


